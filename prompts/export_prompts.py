#!/usr/bin/env python3
"""Export the nine LLM system prompts (P1-P9) as plain text files, with their SHA-256 sums and an index.

The prompts live in the code, as string constants in seven modules; THE CODE IS THE SINGLE SOURCE.  The files next to this script are generated copies for reading, citing and
diffing.  `tests/test_prompts_export.py` fails when a copy differs from its constant, so an edited prompt cannot be committed without regenerating them.

    python prompts/export_prompts.py --write     regenerate prompts/P*.txt, SHA256SUMS and INDEX.md from the code
    python prompts/export_prompts.py --check     exit 1 if anything in prompts/ differs from what the code would export (the test calls this)

Editing a prompt: change the constant, bump its version constant if it has one (P4, P6, P7, P9: the cache keys of those four do not contain the prompt text), run --write, commit.
"""
import argparse
import hashlib
import importlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "src"))

# P-number -> (module, constant, role, version constant or None)
WHERE = {
    "P1": ("cgscout.planning.scientific_planner", "PLANNER_SYSTEM_PROMPT", "scientific planner", None),
    "P2": ("cgscout.planning.expert_prior_planner", "EXPERT_PRIOR_SYSTEM_PROMPT", "expert prior", None),
    "P3": ("cgscout.retrieval.related_systems.terminology", "TERMINOLOGY_EXPANDER_SYSTEM_PROMPT", "terminology expander", None),
    "P4": ("cgscout.retrieval.related_systems.semantic_intent", "_SYSTEM_PROMPT", "Hop-1 semantic sentence", "_PROMPT_VERSION"),
    "P5": ("cgscout.retrieval.related_systems.extraction", "RICH_SYSTEM_EXTRACTION_SYSTEM_PROMPT", "Hop-1 system extraction", None),
    "P6": ("cgscout.retrieval.related_systems.hop2", "_SYSTEM_PROMPT", "Hop-2 anchor normalisation", "_PROMPT_VERSION"),
    "P7": ("cgscout.assessment.stage4", "_SCREEN_SYSTEM", "Stage 4 tier-1 screen", "SCREEN_PROMPT_VERSION"),
    "P8": ("cgscout.assessment.stage4", "_SYSTEM_PROMPT", "Stage 4 fact extraction", None),
    "P9": ("cgscout.assessment.stage4", "_JUDGE_SYSTEM", "Stage 4 tier-2 judge", "JUDGE_PROMPT_VERSION"),
}


def filename(key: str) -> str:
    return f"{key}_{WHERE[key][1].strip('_').lower()}.txt"


def sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def render() -> dict:
    """{file name: text} for every generated file, from the code as it is now."""
    files, rows = {}, []
    for key, (mod, attr, role, ver) in WHERE.items():
        m = importlib.import_module(mod)
        text = getattr(m, attr)
        files[filename(key)] = text
        version = getattr(m, ver) if ver else "(none: the cache key uses the prompt text)"
        rows.append(f"| {key} | {role} | `{mod.replace('cgscout.', '')}.{attr}` | {len(text)} | `{sha256(text)}` | {version} |")
    files["SHA256SUMS"] = "".join(f"{sha256(files[filename(k)])}  {filename(k)}\n" for k in WHERE)
    files["INDEX.md"] = ("# Prompt index\n\nGenerated by `export_prompts.py` from the code (the code is the source; do not edit by hand).\n\n"
                         "| prompt | role | code symbol | characters | sha256 | version constant |\n|---|---|---|---|---|---|\n" + "\n".join(rows) + "\n")
    return files


def check() -> list:
    problems, files = [], render()
    for name, text in files.items():
        p = HERE / name
        if not p.is_file():
            problems.append(f"missing: {name}")
        elif p.read_bytes() != text.encode("utf-8"):
            problems.append(f"differs from the code: {name}")
    extra = sorted(p.name for p in HERE.glob("P[0-9]_*.txt") if p.name not in files)
    problems += [f"not a prompt of the code: {n}" for n in extra]
    return problems


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    if a.write:
        files = render()
        for old in HERE.glob("P[0-9]_*.txt"):
            if old.name not in files:
                old.unlink()
        for name, text in files.items():
            (HERE / name).write_bytes(text.encode("utf-8"))
        print(f"wrote {len(files)} files to {HERE}")
        return 0
    problems = check()
    for p in problems:
        print(p)
    print("prompts/ is in sync with the code" if not problems else f"{len(problems)} problem(s): run `python prompts/export_prompts.py --write`")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
